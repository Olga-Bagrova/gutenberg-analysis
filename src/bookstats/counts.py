def messy_sample(x: int, y: int) -> int:
    """Compute the sum of two integers for testing pre-commit.

    Parameters
    ----------
    x : int
        First integer addend.
    y : int
        Second integer addend.

    Returns
    -------
    int
        Sum of x and y.
    """
    z = x + y
    return z
